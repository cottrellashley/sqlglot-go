# Emits a Go EXPRESSION_METADATA table from the records produced by gen_typing.py.
# Usage: emit_typing.py records.json funcname mapping.py
import json, sys, re
rows = json.load(open(sys.argv[1]))
funcname = sys.argv[2]
ns = {}
exec(open(sys.argv[3]).read(), ns)
MAP = ns["MAP"]
header = ns.get("HEADER", "")

def dtype(name):
    return "exp.DType" + "".join(p[:1].upper() + p[1:].lower() for p in name.split("_"))

def norm(src):
    if src.startswith("FN:"):
        return src
    i = src.find("lambda")
    s = src[i:]
    s = re.sub(r"\s+", "", s)
    s = s.rstrip(",").rstrip("}")
    return s

out = []
missing = []
for r in rows:
    if r["kind"] == "returns":
        out.append(f"\t\tm[exp.{r['cls']}] = &ExprMetadata{{Returns: {dtype(r['dtype'])}}}")
    elif r["kind"] == "returns_expr":
        out.append(f"\t\tm[exp.{r['cls']}] = &ExprMetadata{{Returns: exp.MustDataTypeBuild({json.dumps(r['sql'])}, nil, false)}}")
    elif r["kind"] == "annotator":
        k = norm(r["src"])
        go = MAP.get(k)
        if go is None:
            missing.append(k)
            out.append(f"\t\t// TODO {r['cls']}: {k}")
        else:
            out.append(f"\t\tm[exp.{r['cls']}] = &ExprMetadata{{Annotator: {go}}}")
if missing:
    print("MISSING:", file=sys.stderr)
    for m in sorted(set(missing)):
        print(repr(m), file=sys.stderr)
print("// Code generated by tools/port/emit_typing.py; DO NOT EDIT.\n\npackage sqlglot\n\nimport \"github.com/cottrellashley/sqlglot-go/exp\"\n")
print(header)
print(f"func {funcname}(m map[exp.Kind]*ExprMetadata) {{")
print("\t{")
print("\n".join(out))
print("\t}")
print("}")
