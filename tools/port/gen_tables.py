"""Generates the Go tables (expression kinds, data types, token types) from a sqlglot checkout.

Usage: python3 -I tools/port/gen_tables.py <path-to-sqlglot-checkout> <path-to-sqlglot-go>

This is a porting aid: the generated Go files are committed, so building the Go module never
requires Python. Re-run it when syncing with a newer upstream sqlglot release.
"""
import enum
import os
import sys

SQLGLOT, OUT = sys.argv[1], sys.argv[2]
sys.path.insert(0, SQLGLOT)

import logging
logging.disable(logging.CRITICAL)

from sqlglot import exp  # noqa: E402
from sqlglot.tokens import TokenType  # noqa: E402

try:
    import subprocess
    VERSION = subprocess.check_output(["git", "-C", SQLGLOT, "describe", "--tags", "--always"], text=True).strip()
except Exception:
    VERSION = "unknown"

HEADER = f"// Code generated by tools/port/gen_tables.py from sqlglot {VERSION}; DO NOT EDIT.\n\n"


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:].lower() for p in name.split("_") if p)


def go_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def kind_name(cls) -> str:
    n = cls.__name__
    if n.startswith("_"):
        return n[1:] + "Base"
    return n


# ---------------------------------------------------------------- token types
tt_names = [m.name for m in TokenType]
go_tt = {}
for n in tt_names:
    g = camel(n)
    assert g not in go_tt.values(), (n, g)
    go_tt[n] = g
reserved_tokens_pkg = {"Token", "Tokenizer", "TokenType", "TokenSet", "Config", "Tokenize", "New", "Options"}
for g in go_tt.values():
    assert g not in reserved_tokens_pkg, g

with open(os.path.join(OUT, "tokens", "tokentype_gen.go"), "w") as f:
    f.write(HEADER)
    f.write("package tokens\n\n")
    f.write("// TokenType enumerates the token kinds produced by the tokenizer.\n")
    f.write("// Names mirror sqlglot's TokenType members (L_PAREN -> LParen).\n")
    f.write("const (\n\tInvalid TokenType = iota\n")
    for n in tt_names:
        f.write(f"\t{go_tt[n]}\n")
    f.write("\tnumTokenTypes\n)\n\n")
    f.write("// NumTokenTypes is the number of token types (including Invalid).\nconst NumTokenTypes = int(numTokenTypes)\n\n")
    f.write("var tokenTypeNames = [...]string{\n\tInvalid: \"INVALID\",\n")
    for n in tt_names:
        f.write(f"\t{go_tt[n]}: {go_str(n)},\n")
    f.write("}\n\n")
    f.write("var tokenTypeByName = map[string]TokenType{\n")
    for n in tt_names:
        f.write(f"\t{go_str(n)}: {go_tt[n]},\n")
    f.write("}\n")

# ---------------------------------------------------------------- data types
DType = exp.DType
dt_members = list(DType)
with open(os.path.join(OUT, "exp", "dtypes_gen.go"), "w") as f:
    f.write(HEADER)
    f.write("package exp\n\n")
    f.write("// Data types (sqlglot's exp.DType / exp.DataType.Type).\nconst (\n")
    for m in dt_members:
        f.write(f"\tDType{camel(m.name)} DType = {go_str(m.value)}\n")
    f.write(")\n\n")
    f.write("// AllDTypes lists every data type in declaration order.\nvar AllDTypes = []DType{\n")
    for m in dt_members:
        f.write(f"\tDType{camel(m.name)},\n")
    f.write("}\n\n")
    # DataType class-level sets
    for attr in sorted(vars(exp.DataType)):
        v = getattr(exp.DataType, attr)
        if attr.isupper() and isinstance(v, (set, frozenset)) and all(isinstance(x, DType) for x in v):
            go = "DataType" + camel(attr)
            members = sorted(v, key=lambda m: dt_members.index(m))
            f.write(f"// {go} mirrors exp.DataType.{attr}.\nvar {go} = NewTypeSet(\n")
            for m in members:
                f.write(f"\tDType{camel(m.name)},\n")
            f.write(")\n\n")

# ---------------------------------------------------------------- kinds
classes = sorted(exp.EXPR_CLASSES.values(), key=lambda c: kind_name(c))
classes = [c for c in classes if c.__name__ not in ("Expr", "Expression")]
names = [kind_name(c) for c in classes]
assert len(set(names)) == len(names)
index = {c: i for i, c in enumerate(classes)}
all_funcs = set(exp.ALL_FUNCTIONS)

with open(os.path.join(OUT, "exp", "kinds_gen.go"), "w") as f:
    f.write(HEADER)
    f.write("package exp\n\n")
    f.write("// Expression kinds, one per sqlglot expression class.\nconst (\n\tInvalidKind Kind = iota\n")
    for n in names:
        f.write(f"\t{n}\n")
    f.write("\tnumKinds\n)\n\n")
    f.write("var kindTable = [kindCap]kindInfo{\n")
    for c in classes:
        n = kind_name(c)
        mro = [b for b in c.__mro__[1:] if b in index]
        args = ", ".join(f"{{{go_str(k)}, {'true' if v else 'false'}}}" for k, v in c.arg_types.items())
        fields = [f"name: {go_str(c.__name__)}", f"key: {go_str(c.key)}", f"args: []ArgSpec{{{args}}}"]
        if mro:
            fields.append("bases: []Kind{" + ", ".join(kind_name(b) for b in mro) + "}")
        if c in all_funcs:
            fields.append("isFunc: true")
            fields.append("sqlNames: []string{" + ", ".join(go_str(s) for s in c.sql_names()) + "}")
        if getattr(c, "is_var_len_args", False):
            fields.append("varLen: true")
        vk = getattr(c, "var_len_arg_key", "expressions")
        if vk != "expressions":
            fields.append(f"varLenKey: {go_str(vk)}")
        for flag, go in (("is_primitive", "primitive"), ("_hash_raw_args", "hashRawArgs"), ("is_subquery", "isSubquery"), ("is_cast", "isCast"), ("is_data_type", "isDataType")):
            if getattr(c, flag, False) is True:
                fields.append(f"{go}: true")
        f.write(f"\t{n}: {{" + ", ".join(fields) + "},\n")
    f.write("}\n\n")
    # function registry order (mirrors exp.ALL_FUNCTIONS, which is sorted by class name)
    f.write("// allFunctions mirrors exp.ALL_FUNCTIONS (order matters for name collisions).\nvar allFunctions = []Kind{\n")
    for c in exp.ALL_FUNCTIONS:
        f.write(f"\t{kind_name(c)},\n")
    f.write("}\n")

print(f"token types: {len(tt_names)}, dtypes: {len(dt_members)}, kinds: {len(classes)}, functions: {len(exp.ALL_FUNCTIONS)}")

# ---------------------------------------------------------------- method resolution tables
# For polymorphic properties/methods, record which class (per Python's MRO) provides the
# implementation for every kind. Kinds resolving to Expr/Expression get no entry.
POLY = [
    "name", "output_name", "alias_or_name", "is_star", "selects", "named_selects", "parts",
    "to_py", "is_type", "unnest", "ctes", "kind", "unit", "select", "where", "with_", "from_",
    "isin", "is_number",
]
with open(os.path.join(OUT, "exp", "resolve_gen.go"), "w") as f:
    f.write(HEADER)
    f.write("package exp\n\n")
    for meth in POLY:
        entries = []
        for c in classes:
            for b in c.__mro__:
                if meth in b.__dict__:
                    if b.__name__ not in ("Expr", "Expression"):
                        entries.append((kind_name(c), kind_name(b)))
                    break
        go = "impl" + camel(meth)
        f.write(f"// {go} maps each kind to the class implementing `{meth}` (InvalidKind = Expression default).\n")
        f.write(f"var {go} = [kindCap]Kind{{\n")
        for k, v in entries:
            f.write(f"\t{k}: {v},\n")
        f.write("}\n\n")
    f.write("// implTables lists the resolution tables, so that registered kinds inherit their entries.\n")
    f.write("var implTables = []*[kindCap]Kind{" + ", ".join("&impl" + camel(m) for m in POLY) + "}\n")
print("resolution tables written")

subprocess.run(["gofmt", "-w", os.path.join(OUT, "exp"), os.path.join(OUT, "tokens")], check=True)
