"""Generates exp/modules_gen.go: the Python module of every expression class (for messages
such as "<class 'sqlglot.expressions.core.Paren'>").

Usage: python3 -I gen_modules.py <path to the sqlglot python checkout> <go module root>
"""

import os
import subprocess
import sys

SQLGLOT, OUT = sys.argv[1], sys.argv[2]
sys.path.insert(0, SQLGLOT)

import logging  # noqa: E402

logging.disable(logging.CRITICAL)

from sqlglot import exp  # noqa: E402


def kind_name(cls) -> str:
    n = cls.__name__
    return n[1:] + "Base" if n.startswith("_") else n


classes = sorted(exp.EXPR_CLASSES.values(), key=kind_name)
classes = [c for c in classes if c.__name__ not in ("Expr", "Expression")]
path = os.path.join(OUT, "exp", "modules_gen.go")
with open(path, "w") as f:
    f.write("// Code generated by tools/port/gen_modules.py; DO NOT EDIT.\n\npackage exp\n\n")
    f.write("// kindModule is the Python module defining each expression class.\n")
    f.write("var kindModule = [kindCap]string{\n")
    for c in classes:
        f.write(f'\t{kind_name(c)}: "{c.__module__}",\n')
    f.write("}\n")
subprocess.run(["gofmt", "-w", path], check=True)
print(f"{len(classes)} classes")
